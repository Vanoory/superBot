def build_signal_prompt(symbol: str, side: str, interval: str, entry_zone: str, targets: str, stop: str, confluence: str, commentary_hint: str | None) -> str:
    extra = f"\nЛичный контекст автора: {commentary_hint}" if commentary_hint else ""
    return (
        f"Напиши текст для сигнального поста по {symbol}.\n"
        f"Сторона: {side}. Таймфрейм: {interval}.\n"
        f"Зона набора: {entry_zone}. Цели: {targets}. Стоп: {stop}.\n"
        f"Аргументы сетапа: {confluence}.{extra}\n"
        "Нужно 2-4 предложения комментария к сигналу. Пиши так, как это сделал бы автор канала."
    )


def build_morning_prompt(context: str, symbol: str, price: str, watchlist: str, variant: str) -> str:
    if variant == "analysis":
        variant_hint = "Сделай расширенный утренний пост с мини-разбором: контекст рынка, ключевые уровни, что отслеживать, возможный сценарий."
        length_hint = "Объём: 6-10 предложений."
    else:
        variant_hint = "Сделай обычный утренний пост без глубокого разбора."
        length_hint = "Объём: 4-6 коротких предложений."
    return (
        "Напиши утренний пост для трейдерского канала.\n"
        "Начни с уместного приветствия, если это соответствует стилю канала.\n"
        f"Формат: {variant_hint}\n"
        f"Контекст рынка: {context}\n"
        f"Базовый инструмент: {symbol}, текущая цена: {price}.\n"
        f"Что отслеживать сегодня: {watchlist}\n"
        f"{length_hint}"
    )


def build_filler_prompt(snapshot: str) -> str:
    return (
        "Напиши короткий промежуточный пост для канала между основными публикациями.\n"
        f"Контекст рынка: {snapshot}\n"
        "Нужно 2-4 предложения без занудства, с естественной интонацией автора."
    )


def build_news_prompt(summary: str) -> str:
    return (
        "Напиши 1-2 финальные фразы после списка важных новостей.\n"
        f"Контекст: {summary}\n"
        "Фразы должны звучать как продолжение живого поста канала."
    )


def build_ad_prompt(exchange_name: str, promo_text: str, bonus: str | None, link: str) -> str:
    bonus_line = f"Бонус: {bonus}." if bonus else ""
    return (
        "Перепиши рекламную интеграцию в стиле канала.\n"
        f"Биржа: {exchange_name}. {bonus_line}\n"
        f"Сырой текст: {promo_text}\n"
        f"Ссылка: {link}\n"
        "Сделай это нативно, как будто автор сам рекомендует оффер аудитории."
    )
